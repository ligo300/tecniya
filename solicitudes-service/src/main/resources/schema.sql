CREATE TABLE IF NOT EXISTS solicitud (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        BIGINT        NOT NULL,
    tipo_equipo       VARCHAR(20)   NOT NULL,
    marca_modelo      VARCHAR(100)  NOT NULL,
    descripcion_falla VARCHAR(500)  NOT NULL,
    presupuesto_ref   NUMERIC(10,2) NOT NULL CHECK (presupuesto_ref > 0),
    estado            VARCHAR(20)   NOT NULL,
    creado_en         TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS oferta (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT        NOT NULL REFERENCES solicitud (id) ON DELETE CASCADE,
    tecnico_id   BIGINT        NOT NULL,
    precio       NUMERIC(10,2) NOT NULL CHECK (precio > 0),
    plazo_dias   INT           NOT NULL CHECK (plazo_dias > 0),
    mensaje      VARCHAR(300),
    estado       VARCHAR(20)   NOT NULL,
    creado_en    TIMESTAMP     NOT NULL,
    CONSTRAINT uq_oferta_solicitud_tecnico UNIQUE (solicitud_id, tecnico_id)
);
