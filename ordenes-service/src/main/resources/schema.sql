CREATE TABLE IF NOT EXISTS orden (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(20)   NOT NULL UNIQUE,
    cliente_id      BIGINT        NOT NULL,
    tecnico_id      BIGINT        NOT NULL,
    solicitud_id    BIGINT,
    oferta_id       BIGINT UNIQUE,
    origen          VARCHAR(10)   NOT NULL,
    tipo_equipo     VARCHAR(20)   NOT NULL,
    descripcion     VARCHAR(700)  NOT NULL,
    precio_acordado NUMERIC(10,2) NOT NULL CHECK (precio_acordado > 0),
    estado          VARCHAR(20)   NOT NULL,
    creado_en       TIMESTAMP     NOT NULL,
    actualizado_en  TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS orden_historial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id        BIGINT      NOT NULL REFERENCES orden (id) ON DELETE CASCADE,
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20) NOT NULL,
    usuario_id      BIGINT      NOT NULL,
    fecha           TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS orden_foto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id       BIGINT       NOT NULL REFERENCES orden (id) ON DELETE CASCADE,
    estado         VARCHAR(20)  NOT NULL,
    url            VARCHAR(300) NOT NULL,
    nombre_archivo VARCHAR(120) NOT NULL,
    tamano_bytes   BIGINT       NOT NULL,
    subido_por     BIGINT       NOT NULL,
    fecha          TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS pago (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id      BIGINT        NOT NULL REFERENCES orden (id) ON DELETE CASCADE,
    monto         NUMERIC(10,2) NOT NULL CHECK (monto > 0),
    medio         VARCHAR(15)   NOT NULL,
    nro_operacion VARCHAR(40)   NOT NULL UNIQUE,
    estado        VARCHAR(15)   NOT NULL,
    fecha         TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS calificacion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id   BIGINT       NOT NULL UNIQUE REFERENCES orden (id) ON DELETE CASCADE,
    puntaje    INT          NOT NULL CHECK (puntaje BETWEEN 1 AND 5),
    comentario VARCHAR(300),
    fecha      TIMESTAMP    NOT NULL
);
