CREATE TABLE IF NOT EXISTS tecnico (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL UNIQUE,
    nombres        VARCHAR(80)   NOT NULL,
    apellidos      VARCHAR(80)   NOT NULL,
    documento      VARCHAR(20)   NOT NULL UNIQUE,
    telefono       VARCHAR(20)   NOT NULL,
    zona           VARCHAR(80)   NOT NULL,
    tarifa_base    NUMERIC(10,2) NOT NULL CHECK (tarifa_base > 0),
    estado         VARCHAR(25)   NOT NULL,
    calif_promedio NUMERIC(3,2)  NOT NULL DEFAULT 0,
    calif_cantidad INT           NOT NULL DEFAULT 0,
    creado_en      TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS tecnico_especialidad (
    tecnico_id  BIGINT      NOT NULL REFERENCES tecnico (id) ON DELETE CASCADE,
    tipo_equipo VARCHAR(20) NOT NULL,
    PRIMARY KEY (tecnico_id, tipo_equipo)
);
